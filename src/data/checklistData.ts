export function filterChecklistByAuditType(
  items: ChecklistItemDef[],
  auditType: AuditType
): ChecklistItemDef[] {
  if (auditType === 'BOTH') return items;
  return items.filter((item) => item.appliesTo === 'COMMON' || item.appliesTo === auditType);
}
